#!/usr/bin/env node
// Generates THIRD-PARTY-NOTICES.md: the license text of every package whose code is bundled into the web UI that
// ships in the package (dist/web). The set is the runtime dependency closure of react, react-dom and
// react-router-dom from package-lock.json; the texts come from the installed packages (run `npm ci` first).
//
// Usage: node scripts/third-party-notices.mjs           writes THIRD-PARTY-NOTICES.md
//        node scripts/third-party-notices.mjs --check   exits 1 when the file is out of date
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const lock = JSON.parse(readFileSync(resolve(root, "package-lock.json"), "utf8")).packages;
export const BUNDLED_ROOTS = ["react", "react-dom", "react-router-dom"];

/** Runtime (and peer) dependency closure of the bundled roots, sorted by name. */
export function bundledClosure() {
  const seen = new Set();
  const walk = (name) => {
    const entry = lock[`node_modules/${name}`];
    if (!entry || seen.has(name)) return;
    seen.add(name);
    for (const dep of Object.keys(entry.dependencies ?? {})) walk(dep);
    for (const dep of Object.keys(entry.peerDependencies ?? {})) walk(dep);
  };
  for (const name of BUNDLED_ROOTS) walk(name);
  return [...seen].sort().map((name) => ({ name, version: lock[`node_modules/${name}`].version, license: lock[`node_modules/${name}`].license }));
}

function licenseText(name) {
  for (const file of ["LICENSE", "LICENSE.md", "LICENSE.txt", "license"]) {
    const path = resolve(root, "node_modules", name, file);
    // Author e-mail addresses in the notice lines are dropped: the repository's hygiene rule keeps personal
    // addresses out of every file, and the copyright holders' names and years, which the license requires, stay.
    if (existsSync(path)) return readFileSync(path, "utf8").trim().replace(/[ \t]*<[^<>@\s]+@[^<>\s]+>/g, "");
  }
  throw new Error(`no license file found for ${name}; run npm ci first`);
}

export function render() {
  const parts = [
    "# Third-party notices",
    "",
    "The web UI that ships in this package (`dist/web`) bundles the following open source packages. Their license terms require that these notices accompany the distribution. ChangeRadar itself is MIT licensed (see `LICENSE`). The full list of every dependency and its license is in `docs/DEPENDENCY-LICENSES.md`.",
    "",
    "Generated by `scripts/third-party-notices.mjs` from `package-lock.json` and the installed license files; do not edit by hand.",
    "",
  ];
  for (const { name, version, license } of bundledClosure()) {
    parts.push(`## ${name} ${version} (${license})`, "", "```text", licenseText(name), "```", "");
  }
  return parts.join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const target = resolve(root, "THIRD-PARTY-NOTICES.md");
  const generated = render();
  if (process.argv.includes("--check")) {
    const current = existsSync(target) ? readFileSync(target, "utf8") : "";
    if (current !== generated) {
      console.error("THIRD-PARTY-NOTICES.md is out of date; run: node scripts/third-party-notices.mjs");
      process.exit(1);
    }
    console.log("THIRD-PARTY-NOTICES.md is up to date");
  } else {
    writeFileSync(target, generated);
    console.log(`wrote THIRD-PARTY-NOTICES.md (${bundledClosure().length} packages)`);
  }
}
