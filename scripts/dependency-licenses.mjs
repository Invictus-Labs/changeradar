#!/usr/bin/env node
// Generates docs/DEPENDENCY-LICENSES.md from package-lock.json and the installed packages.
// Usage: node scripts/dependency-licenses.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const lock = JSON.parse(readFileSync(resolve(root, "package-lock.json"), "utf8"));
const permissive = /^(MIT|MIT-0|ISC|BSD-2-Clause|BSD-3-Clause|Apache-2\.0|0BSD|BlueOak-1\.0\.0|Python-2\.0|CC0-1\.0|Unlicense)$/;

function licenseOf(meta) {
  const raw = meta.license ?? meta.licenses;
  if (typeof raw === "string") return raw;
  if (raw && typeof raw === "object" && !Array.isArray(raw)) return raw.type ?? "UNKNOWN";
  if (Array.isArray(raw)) return raw.map((l) => l.type ?? l).join(" OR ");
  return "UNKNOWN";
}

function allowed(expression) {
  // Accept SPDX "A OR B" and "(A OR B)" when at least one alternative is permissive, and "A AND B" only when all are.
  const cleaned = expression.replace(/[()]/g, "");
  if (cleaned.includes(" AND ")) return cleaned.split(" AND ").every((p) => permissive.test(p.trim()));
  return cleaned.split(" OR ").some((p) => permissive.test(p.trim()));
}

// Reviewed exceptions: development-only packages under a weak (file level) copyleft license.
// They are never bundled into or distributed with the product. Each entry needs a written reason.
const reviewedExceptions = [
  {
    match: /^lightningcss(-.+)?$/,
    license: "MPL-2.0",
    reason:
      "MPL-2.0 is file-level copyleft. lightningcss is a development-only transitive dependency of vite and is its default CSS minifier: it runs when the web UI is built, and its code is not part of the built output or the package, so no MPL obligations attach to the product.",
  },
];
const exceptionFor = (r) =>
  r.scope === "dev" ? reviewedExceptions.find((e) => e.match.test(r.name) && e.license === r.license) : undefined;

const rows = [];
for (const [path, info] of Object.entries(lock.packages)) {
  if (path === "") continue;
  const name = path.replace(/^.*node_modules\//, "");
  let meta = {};
  try {
    meta = JSON.parse(readFileSync(resolve(root, path, "package.json"), "utf8"));
  } catch {
    // Optional platform packages that are not installed on this machine keep the lockfile license, if any.
    meta = { license: info.license };
  }
  const license = licenseOf(meta);
  rows.push({ name, version: info.version, license, scope: info.dev ? "dev" : "runtime", optional: Boolean(info.optional) });
}
rows.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const flagged = rows.filter((r) => !allowed(r.license));
const bad = flagged.filter((r) => !exceptionFor(r));
const excepted = flagged.filter((r) => exceptionFor(r));
const runtime = rows.filter((r) => r.scope === "runtime");
const lines = [
  "# Dependency license audit",
  "",
  "Generated by `node scripts/dependency-licenses.mjs` from `package-lock.json` and the installed packages. Do not edit by hand.",
  "",
  `- Packages audited: ${rows.length} (${runtime.length} runtime, ${rows.length - runtime.length} development-only)`,
  `- Unreviewed non-permissive or unknown licenses: ${bad.length === 0 ? "none" : bad.map((r) => `${r.name}@${r.version} (${r.license})`).join(", ")}`,
  `- Reviewed exceptions: ${excepted.length === 0 ? "none" : `${excepted.length} package(s), all development-only (see below)`}`,
  "- Policy: MIT, ISC, BSD, Apache-2.0 and equivalent permissive licenses only. A copyleft or unknown license blocks release until reviewed.",
  "- The product license is MIT (see `LICENSE`).",
  "",
  ...(excepted.length === 0
    ? []
    : [
        "## Reviewed exceptions",
        "",
        ...reviewedExceptions.map((e) => `- \`${e.match.source}\` (${e.license}): ${e.reason}`),
        "",
      ]),
  "## All packages",
  "",
  "| Package | Version | License | Scope |",
  "| --- | --- | --- | --- |",
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.scope}${r.optional ? " (optional)" : ""}${exceptionFor(r) ? " (reviewed exception)" : ""} |`),
  "",
];
const output = lines.join("\n");
const target = resolve(root, "docs", "DEPENDENCY-LICENSES.md");

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // Missing counts as drift.
  }
  if (current !== output) {
    console.error("docs/DEPENDENCY-LICENSES.md is out of date; run: node scripts/dependency-licenses.mjs");
    process.exit(1);
  }
  process.exit(bad.length === 0 ? 0 : 1);
}
writeFileSync(target, output);
console.log(`wrote docs/DEPENDENCY-LICENSES.md (${rows.length} packages, ${bad.length} non-permissive)`);
process.exit(bad.length === 0 ? 0 : 1);
